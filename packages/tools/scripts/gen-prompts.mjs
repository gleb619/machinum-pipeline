// Compiles packages/tools/prompts/*.md into src/generated/prompts.ts.
//
// The prompt texts must ship inside the built package (and inside the single-file `mt`
// binary), so they are compiled into a TS module at build time instead of being read
// from disk at runtime. The key of a prompt is its file name without the `.md` suffix
// (`prompts/summary.user.md` -> `summary.user`).
//
// Run: node scripts/gen-prompts.mjs (wired into the build/typecheck/test scripts).
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const promptsDir = join(root, 'prompts')
const outFile = join(root, 'src', 'generated', 'prompts.ts')

const files = readdirSync(promptsDir)
  .filter((name) => name.endsWith('.md'))
  .sort()

if (files.length === 0) {
  throw new Error(`gen-prompts: no prompt files in ${promptsDir}`)
}

/** Single-quoted JS string literal, Biome formatting style (quotes, escapes, `\n` kept). */
function literal(text) {
  const escaped = text
    .replace(/\\/g, '\\\\')
    .replace(/\t/g, '\\t')
    .replace(/\r/g, '\\r')
    .replace(/\n/g, '\\n')
    .replace(/'/g, "\\'")
  return `'${escaped}'`
}

const entries = files.map((name) => {
  const key = name.replace(/\.md$/, '')
  const text = readFileSync(join(promptsDir, name), 'utf8').replace(/\s+$/, '')
  // Biome moves a value that does not fit the line onto its own indented line.
  return `  ${literal(key)}:\n    ${literal(text)},`
})

const module = `// AUTO-GENERATED by scripts/gen-prompts.mjs - do not edit by hand.
// Source: packages/tools/prompts/*.md (regenerate with \`pnpm --filter=@mt/tools gen:prompts\`).

/** Every bundled prompt, keyed by its file name without the \`.md\` suffix. */
export const BUNDLED_PROMPTS = {
${entries.join('\n')}
} as const
`

mkdirSync(dirname(outFile), { recursive: true })
const previous = existsSync(outFile) ? readFileSync(outFile, 'utf8') : ''
if (previous === module) {
  console.log(`gen-prompts: ${files.length} prompt(s) up to date`)
} else {
  writeFileSync(outFile, module)
  console.log(`gen-prompts: wrote ${files.length} prompt(s) to src/generated/prompts.ts`)
}
