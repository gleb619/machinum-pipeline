// Generate src/generated/skill-content.ts from docs/SKILL.md (the single source of truth).
// Usage: node scripts/gen-skill.mjs [--check]
//   --check  exit 1 when the committed copy differs (no write)
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const source = resolve(root, '..', '..', 'docs', 'SKILL.md')
const target = join(root, 'src', 'generated', 'skill-content.ts')

const text = readFileSync(source, 'utf-8')
const version = /skill-version:\s*([^\s|]+)/.exec(text)?.[1] ?? 'unknown'

/** TS string literal in the quote style Biome would pick (fewer escapes wins, single on a tie). */
const quote = (s) => {
  const singles = (s.match(/'/g) ?? []).length
  const doubles = (s.match(/"/g) ?? []).length
  const q = singles > doubles ? '"' : "'"
  let out = ''
  for (const ch of s) {
    if (ch === '\\') out += '\\\\'
    else if (ch === q) out += `\\${q}`
    else if (ch === '\n') out += '\\n'
    else if (ch === '\r') out += '\\r'
    else if (ch === '\u2028') out += '\\u2028'
    else if (ch === '\u2029') out += '\\u2029'
    else out += ch
  }
  return `${q}${out}${q}`
}

/** `export const NAME = <literal>`; a line over Biome's 100 columns breaks after `=`. */
const decl = (name, literal) => {
  const line = `export const ${name} = ${literal}`
  return line.length > 100 ? `export const ${name} =\n  ${literal}` : line
}

const out = `// @generated by scripts/gen-skill.mjs from docs/SKILL.md - do not edit; run \`pnpm --filter=@mt/cli gen:skill\`
export const SKILL_SOURCE = 'docs/SKILL.md'
${decl('SKILL_VERSION', quote(version))}
${decl('SKILL_MD', quote(text))}
`

if (process.argv.includes('--check')) {
  let current = ''
  try {
    current = readFileSync(target, 'utf-8')
  } catch {
    // missing file counts as stale
  }
  if (current !== out) {
    console.error('skill-content.ts is stale: run `pnpm --filter=@mt/cli gen:skill`')
    process.exit(1)
  }
} else {
  mkdirSync(dirname(target), { recursive: true })
  writeFileSync(target, out)
}
